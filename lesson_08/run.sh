#!/bin/bash
# Шебанг: говорит оболочке, что этот файл нужно выполнять через bash.
# Нужен, чтобы скрипт можно было сделать исполняемым (chmod +x run.sh) и запускать как ./run.sh
# # - в английском это hash (решётка), ! - это bang (восклицательный знак). Поэтому Шебанг

echo "========================================"
echo "Установка виртуального окружения..."
echo "========================================"
# Создаём изолированное окружение в папке .venv
# В Unix-системах это стандарт для изоляции зависимостей проекта.
python3 -m venv .venv

# Активируем окружение: теперь команды python/pip будут использовать файлы из .venv.
# source — это способ выполнить скрипт активации в текущей сессии (не открывая новую оболочку).
source .venv/bin/activate

# Устанавливаем зависимости из requirements.txt внутри виртуального окружения.
pip install -r requirements.txt

echo "========================================"
echo "Настройка .env (если нужно)"
echo "========================================"
# Запускаем скрипт настройки: он создаст .env и API-ключ, если их нет.
# Если ключ уже есть — скрипт не будет перезаписывать их без нужды.
python3 setup_env.py

echo "========================================"
echo "Запуск тестов..."
echo "========================================"
# pytest -v — подробный вывод: видно каждый тест, его имя и статус.
pytest tests/test_projects.py -v
